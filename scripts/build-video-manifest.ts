/**
 * Scans public/videos for video files and emits a manifest with intrinsic
 * dimensions + a tiny base64 first-frame blur, so the shared <Video>
 * component can reserve space and render a blur-up poster.
 *
 * Output: src/videoMap.gen.ts
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname!, "..");
const PUBLIC_DIR = path.join(ROOT, "public");
const VIDEOS_DIR = path.join(PUBLIC_DIR, "videos");
const OUTPUT_PATH = path.join(ROOT, "src/videoMap.gen.ts");

const VIDEO_EXT = new Set([".webm", ".mp4", ".mov", ".m4v"]);

interface Entry {
  width: number;
  height: number;
  blurDataURL: string | null;
}

function walk(dir: string, out: string[] = []): string[] {
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    const stat = fs.statSync(full);
    if (stat.isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
}

function probeDimensions(absPath: string): { width: number; height: number } | null {
  try {
    const json = execFileSync(
      "ffprobe",
      [
        "-v",
        "error",
        "-select_streams",
        "v:0",
        "-show_entries",
        "stream=width,height",
        "-of",
        "json",
        absPath,
      ],
      { encoding: "utf-8" },
    );
    const data = JSON.parse(json);
    const stream = data.streams?.[0];
    if (!stream?.width || !stream?.height) return null;
    return { width: stream.width, height: stream.height };
  } catch {
    return null;
  }
}

async function extractBlur(absPath: string): Promise<string | null> {
  const tmp = path.join(os.tmpdir(), `mediamanifest-${process.pid}-${Date.now()}.png`);
  try {
    execFileSync(
      "ffmpeg",
      ["-y", "-v", "error", "-i", absPath, "-vf", "select=eq(n\\,0)", "-vframes", "1", tmp],
      { stdio: ["ignore", "ignore", "ignore"] },
    );
    if (!fs.existsSync(tmp)) return null;
    const buf = await sharp(tmp)
      .resize(40, undefined, { fit: "inside" })
      .jpeg({ quality: 45 })
      .toBuffer();
    return `data:image/jpeg;base64,${buf.toString("base64")}`;
  } catch {
    return null;
  } finally {
    if (fs.existsSync(tmp)) fs.unlinkSync(tmp);
  }
}

async function processVideo(absPath: string): Promise<[string, Entry] | null> {
  const ext = path.extname(absPath).toLowerCase();
  if (!VIDEO_EXT.has(ext)) return null;

  const dims = probeDimensions(absPath);
  if (!dims) return null;
  const blurDataURL = await extractBlur(absPath);

  const publicPath = "/" + path.relative(PUBLIC_DIR, absPath).split(path.sep).join("/");
  return [publicPath, { width: dims.width, height: dims.height, blurDataURL }];
}

async function main() {
  if (!fs.existsSync(VIDEOS_DIR)) {
    console.warn(`[video-manifest] ${VIDEOS_DIR} does not exist, skipping`);
    return;
  }

  const files = walk(VIDEOS_DIR);
  const entries = await Promise.all(files.map(processVideo));
  const manifest: Record<string, Entry> = {};
  for (const e of entries) {
    if (e) manifest[e[0]] = e[1];
  }

  const sorted = Object.keys(manifest).sort();
  const body = sorted
    .map((k) => {
      const { width, height, blurDataURL } = manifest[k];
      const blur = blurDataURL === null ? "null" : JSON.stringify(blurDataURL);
      return `  ${JSON.stringify(k)}: { width: ${width}, height: ${height}, blurDataURL: ${blur} },`;
    })
    .join("\n");

  const source = `// Generated by scripts/build-video-manifest.ts — do not edit by hand.
export interface VideoManifestEntry {
  width: number;
  height: number;
  blurDataURL: string | null;
}

export const videoManifest: Record<string, VideoManifestEntry> = {
${body}
};
`;

  fs.writeFileSync(OUTPUT_PATH, source);
  console.log(`[video-manifest] wrote ${sorted.length} entries to ${path.relative(ROOT, OUTPUT_PATH)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
